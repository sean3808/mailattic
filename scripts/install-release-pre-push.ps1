<#
.SYNOPSIS
  Install the release-tag guard into the active Git pre-push chain.

.DESCRIPTION
  pre-commit consumes raw pre-push stdin before normal hook entries run. This
  installer uses pre-commit's supported pre-push.legacy companion so the
  release-tag guard sees every pushed ref, including atomic main + tag pushes.
#>

param(
    [string]$RepoRoot,
    [string]$PythonProjectRoot,
    [string]$GuardScriptPath
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8

$marker = '# bes-release-pre-push v1'
$generatedMarker = 'File generated by pre-commit: https://pre-commit.com'

function Get-GitHooksPath {
    param(
        [Parameter(Mandatory)]
        [string]$RepoRoot
    )

    Push-Location -LiteralPath $RepoRoot
    try {
        $rawPath = @(& git rev-parse --git-path hooks 2>&1)
        if ($LASTEXITCODE -ne 0) {
            throw "Unable to resolve Git hooks path for '$RepoRoot'."
        }
    } finally {
        Pop-Location
    }

    $hooksPath = (($rawPath | ForEach-Object { $_.ToString() }) -join '').Trim()
    if (-not [IO.Path]::IsPathRooted($hooksPath)) {
        $hooksPath = Join-Path $RepoRoot $hooksPath
    }
    return [IO.Path]::GetFullPath($hooksPath)
}

function Install-ReleasePrePush {
    param(
        [Parameter(Mandatory)]
        [string]$RepoRoot,
        [Parameter(Mandatory)]
        [string]$PythonProjectRoot,
        [Parameter(Mandatory)]
        [string]$GuardScriptPath
    )

    $resolvedRepo = (Resolve-Path -LiteralPath $RepoRoot).Path
    $resolvedProject = (Resolve-Path -LiteralPath $PythonProjectRoot).Path
    $resolvedGuard = (Resolve-Path -LiteralPath $GuardScriptPath).Path
    $hooksPath = Get-GitHooksPath -RepoRoot $resolvedRepo
    $wrapperPath = Join-Path $hooksPath 'pre-push'
    $legacyPath = Join-Path $hooksPath 'pre-push.legacy'

    if (Test-Path -LiteralPath $legacyPath) {
        $legacyContent = Get-Content -LiteralPath $legacyPath -Raw
        if (-not $legacyContent.Contains($marker)) {
            throw (
                "Refusing to replace unrelated pre-push.legacy hook: $legacyPath. " +
                'Move or integrate that hook explicitly, then run this installer again.'
            )
        }
    }

    if (Test-Path -LiteralPath $wrapperPath) {
        $wrapperContent = Get-Content -LiteralPath $wrapperPath -Raw
        if (-not $wrapperContent.Contains($generatedMarker)) {
            throw (
                "Refusing to replace unrelated pre-push hook: $wrapperPath. " +
                'Move or integrate that hook explicitly, then run this installer again.'
            )
        }
    }

    Push-Location -LiteralPath $resolvedRepo
    try {
        $gitDirOutput = @(& git rev-parse --git-dir 2>&1)
        if ($LASTEXITCODE -ne 0) {
            throw "Unable to resolve Git directory for '$resolvedRepo'."
        }
        $localHooksPathValues = @(& git config --local --get-all core.hooksPath 2>$null)
        $localHooksPathExitCode = $LASTEXITCODE
        if ($localHooksPathExitCode -notin @(0, 1)) {
            throw 'Unable to inspect local core.hooksPath.'
        }
    } finally {
        Pop-Location
    }

    $gitDir = (($gitDirOutput | ForEach-Object { $_.ToString() }) -join '').Trim()
    if (-not [IO.Path]::IsPathRooted($gitDir)) {
        $gitDir = Join-Path $resolvedRepo $gitDir
    }
    $defaultHooksPath = [IO.Path]::GetFullPath((Join-Path $gitDir 'hooks'))
    if (
        $localHooksPathValues.Count -gt 0 -and
        -not [StringComparer]::OrdinalIgnoreCase.Equals($hooksPath, $defaultHooksPath)
    ) {
        throw (
            "core.hooksPath points outside the default Git hooks directory: $hooksPath. " +
            'The installer will not modify a custom hooks layout.'
        )
    }

    $restoreLocalHooksPath = $localHooksPathValues.Count -gt 0
    if ($restoreLocalHooksPath) {
        Push-Location -LiteralPath $resolvedRepo
        try {
            & git config --local --unset-all core.hooksPath
            if ($LASTEXITCODE -ne 0) {
                throw 'Unable to temporarily unset local core.hooksPath.'
            }
        } finally {
            Pop-Location
        }
    }

    Push-Location -LiteralPath $resolvedRepo
    try {
        & uv run --project $resolvedProject pre-commit install --hook-type pre-push
        if ($LASTEXITCODE -ne 0) {
            throw "pre-commit pre-push installation failed with exit code $LASTEXITCODE."
        }
    } finally {
        Pop-Location
        if ($restoreLocalHooksPath) {
            Push-Location -LiteralPath $resolvedRepo
            try {
                foreach ($hooksPathValue in $localHooksPathValues) {
                    & git config --local --add core.hooksPath $hooksPathValue.ToString()
                    if ($LASTEXITCODE -ne 0) {
                        throw 'Unable to restore local core.hooksPath.'
                    }
                }
            } finally {
                Pop-Location
            }
        }
    }

    if (-not (Test-Path -LiteralPath $wrapperPath -PathType Leaf)) {
        throw "pre-commit did not create the expected wrapper: $wrapperPath"
    }
    $wrapperContent = Get-Content -LiteralPath $wrapperPath -Raw
    if (-not $wrapperContent.Contains($generatedMarker)) {
        throw "Installed pre-push wrapper is not owned by pre-commit: $wrapperPath"
    }

    Push-Location -LiteralPath $resolvedRepo
    try {
        $pythonOutput = @(
            & uv run --project $resolvedProject python -c 'import sys; print(sys.executable)' 2>&1
        )
        if ($LASTEXITCODE -ne 0) {
            throw "Unable to resolve the project Python with exit code $LASTEXITCODE."
        }
    } finally {
        Pop-Location
    }
    $pythonExecutable = (($pythonOutput | ForEach-Object { $_.ToString() }) -join '').Trim()
    if (-not (Test-Path -LiteralPath $pythonExecutable -PathType Leaf)) {
        throw "Resolved project Python does not exist: $pythonExecutable"
    }

    $pythonShebang = $pythonExecutable.Replace('\', '/')
    $guardLiteral = $resolvedGuard | ConvertTo-Json -Compress
    $launcher = @(
        "#!$pythonShebang"
        $marker
        'from __future__ import annotations'
        'import runpy'
        ('runpy.run_path({0}, run_name="__main__")' -f $guardLiteral)
        ''
    ) -join [char]10
    [IO.File]::WriteAllText(
        $legacyPath,
        $launcher,
        [Text.UTF8Encoding]::new($false)
    )

    $installedLegacy = Get-Content -LiteralPath $legacyPath -Raw
    if (-not $installedLegacy.Contains($marker)) {
        throw "Release pre-push companion verification failed: $legacyPath"
    }

    Write-Host "Installed pre-commit wrapper : $wrapperPath"
    Write-Host "Installed release companion  : $legacyPath"
}

if (-not $RepoRoot) {
    $RepoRoot = Split-Path -Parent $PSScriptRoot
}
if (-not $PythonProjectRoot) {
    $PythonProjectRoot = $RepoRoot
}
if (-not $GuardScriptPath) {
    $GuardScriptPath = Join-Path $RepoRoot 'scripts\guard-release-tag.py'
}

try {
    $installParameters = @{
        RepoRoot = $RepoRoot
        PythonProjectRoot = $PythonProjectRoot
        GuardScriptPath = $GuardScriptPath
    }
    Install-ReleasePrePush @installParameters
} catch {
    [Console]::Error.WriteLine("[install-release-pre-push] ERROR: $($_.Exception.Message)")
    exit 1
}
