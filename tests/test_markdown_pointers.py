"""Every tracked markdown relative link (and #fragment) must resolve (#116).

Canon lives in one place and is pointed to from elsewhere; this is the one
repo-wide check that those pointers are still alive. Known-dead pointers are
frozen in a ratchet baseline: a new dead pointer fails, and a baseline entry
that came back to life fails too, so the list can only shrink.

Regenerate the baseline (after a human looked at the list):
    uv run python -m tests.test_markdown_pointers
"""

import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

from tests.test_agent_pr_contract import _heading_section_ranges

REPO_ROOT = Path(__file__).resolve().parent.parent
BASELINE = Path(__file__).parent / "fixtures" / "dead_markdown_pointers.txt"

FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
INLINE_CODE = re.compile(r"(`+).+?\1", re.DOTALL)
# [text](target "title") / ![alt](<target with spaces>) ; text may nest one [] level.
INLINE_LINK = re.compile(
    r"\]\(\s*(?P<target><[^>\n]*>|[^()\s]*(?:\([^()\s]*\)[^()\s]*)*)"
    r"(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\)"
)
REFERENCE_DEF = re.compile(
    r"^ {0,3}\[[^\]]+\]:[ \t]*(?P<target><[^>]*>|\S+)", re.MULTILINE
)
# URLs, protocol-relative, and local absolute paths like /D:/x/y.py:14 (not repo)
SCHEME = re.compile(r"^(?:[a-zA-Z][a-zA-Z0-9+.\-]*:|//|/[a-zA-Z]:/)")
# Generated by scripts/gen_doc_index.py; a hook regenerates them and by design never
# blocks a commit, so dead pointers inside these blocks are not this check's business.
GENERATED = re.compile(
    r"<!-- BEGIN GENERATED [A-Z\-]+ -->.*?<!-- END GENERATED [A-Z\-]+ -->", re.DOTALL
)


def _strip_fences(markdown: str) -> str:
    """Blank out fenced code blocks (headings and links inside are not real)."""
    out, fence = [], None
    for line in markdown.splitlines():
        match = FENCE.match(line)
        if fence is None and match:
            fence = match.group(1)[0] * len(match.group(1))
            out.append("")
        elif fence is not None:
            if match and line.strip().startswith(fence):
                fence = None
            out.append("")
        else:
            out.append(line)
    return "\n".join(out)


def _anchors(markdown: str) -> set[str]:
    return set(_heading_section_ranges(_strip_fences(markdown)))


def _raw_targets(markdown: str) -> list[str]:
    prose = INLINE_CODE.sub("", _strip_fences(GENERATED.sub("", markdown)))
    targets = [m.group("target") for m in INLINE_LINK.finditer(prose)]
    targets += [m.group("target") for m in REFERENCE_DEF.finditer(prose)]
    return [t[1:-1] if t.startswith("<") else t for t in targets]


def dead_pointers(root: Path, files: list[Path]) -> set[tuple[str, str]]:
    """Return {(source path relative to root, target as written)} of dead pointers."""
    dead = set()
    anchor_cache: dict[Path, set[str]] = {}
    for source in files:
        rel = source.relative_to(root).as_posix()
        for raw in _raw_targets(source.read_text(encoding="utf-8")):
            if not raw or SCHEME.match(raw):
                continue
            path_part, _, fragment = raw.partition("#")
            path_part = unquote(path_part.partition("?")[0])
            if not path_part:
                target = source
            elif path_part.startswith("/"):
                target = root / path_part.lstrip("/")
            else:
                target = source.parent / path_part
            if not target.exists():
                dead.add((rel, raw))
            elif fragment and target.suffix == ".md" and target.is_file():
                if target not in anchor_cache:
                    anchor_cache[target] = _anchors(target.read_text(encoding="utf-8"))
                if unquote(fragment).lower() not in anchor_cache[target]:
                    dead.add((rel, raw))
    return dead


def _tracked_markdown() -> list[Path]:
    names = subprocess.run(
        ["git", "-c", "core.quotepath=false", "ls-files", "-z", "*.md"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        encoding="utf-8",
    ).stdout.split("\0")
    return [p for n in names if n and (p := REPO_ROOT / n).is_file()]


def _read_baseline() -> set[tuple[str, str]]:
    if not BASELINE.exists():
        return set()
    lines = BASELINE.read_text(encoding="utf-8").splitlines()
    return {tuple(line.split("\t", 1)) for line in lines if line}  # type: ignore[misc]


def _format(pairs) -> str:
    return "\n".join(f"  {src}  ->  {target}" for src, target in sorted(pairs))


def test_no_new_dead_markdown_pointers_and_baseline_only_shrinks():
    found = dead_pointers(REPO_ROOT, _tracked_markdown())
    baseline = _read_baseline()
    new = found - baseline
    healed = baseline - found
    assert not new, f"dead markdown pointers not in the baseline:\n{_format(new)}"
    assert not healed, (
        "baseline entries that are no longer dead (delete them from "
        f"{BASELINE.name}):\n{_format(healed)}"
    )


def _tree(tmp_path: Path, files: dict[str, str]) -> list[Path]:
    for name, text in files.items():
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / name).write_text(text, encoding="utf-8")
    return [tmp_path / n for n in files if n.endswith(".md")]


TARGET = "# Title\n\n## 交付 契約\n\n## Dup\n\n## Dup\n"


def test_dead_file_target_is_reported(tmp_path):
    files = _tree(tmp_path, {"a.md": "[x](gone.md)\n", "t.md": TARGET})
    assert dead_pointers(tmp_path, files) == {("a.md", "gone.md")}


def test_dead_fragment_on_existing_file_is_reported(tmp_path):
    files = _tree(tmp_path, {"a.md": "[x](t.md#nope)\n", "t.md": TARGET})
    assert dead_pointers(tmp_path, files) == {("a.md", "t.md#nope")}


def test_dead_same_file_fragment_is_reported(tmp_path):
    files = _tree(tmp_path, {"a.md": "# Here\n\n[x](#missing)\n"})
    assert dead_pointers(tmp_path, files) == {("a.md", "#missing")}


def test_valid_links_in_every_shape_pass(tmp_path):
    body = (
        "# Here\n\n"
        "[a](t.md) [b](t.md#title) [c](#here) [d](t.md#交付-契約) "
        "[e](t.md#%E4%BA%A4%E4%BB%98-%E5%A5%91%E7%B4%84) [f](t.md#dup-1)\n"
        '[g](t.md "a title") [h](<sub dir/f.md>) ![i](img.png) '
        "[j](sub%20dir) [k][ref]\n"
        "[l](https://example.com/x.md) [m](mailto:a@b.c) [n](/t.md#title) "
        "[o](/D:/x/y.py:14)\n\n"
        "[ref]: t.md#title\n"
    )
    files = _tree(
        tmp_path,
        {"a.md": body, "t.md": TARGET, "sub dir/f.md": "# F\n", "img.png": "x"},
    )
    assert dead_pointers(tmp_path, files) == set()


def test_links_in_code_and_headings_in_fences_are_not_real(tmp_path):
    body = (
        "# A\n\n`[x](gone.md)`\n\n```\n[y](gone.md)\n# fenced\n```\n\n"
        "[z](#fenced)\n"
        "<!-- BEGIN GENERATED X -->\n[w](gone.md)\n<!-- END GENERATED X -->\n"
    )
    files = _tree(tmp_path, {"a.md": body})
    assert dead_pointers(tmp_path, files) == {("a.md", "#fenced")}


def test_renamed_target_file_goes_red_with_real_scan(tmp_path):
    files = _tree(tmp_path, {"a.md": "[x](t.md#title)\n", "t.md": TARGET})
    assert dead_pointers(tmp_path, files) == set()
    (tmp_path / "t.md").rename(tmp_path / "t2.md")
    assert dead_pointers(tmp_path, files[:1]) == {("a.md", "t.md#title")}


if __name__ == "__main__":
    if sys.stdout.encoding != "utf-8":
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[attr-defined]
    pairs = dead_pointers(REPO_ROOT, _tracked_markdown())
    BASELINE.parent.mkdir(parents=True, exist_ok=True)
    BASELINE.write_text(
        "".join(f"{s}\t{t}\n" for s, t in sorted(pairs)), encoding="utf-8", newline="\n"
    )
    print(f"wrote {len(pairs)} dead pointers to {BASELINE}")
